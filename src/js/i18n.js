export function resolveLanguage() {
  const queryLanguage = new URLSearchParams(window.location.search).get('lang');
  let storedLanguage = null;

  try {
    storedLanguage = window.localStorage.getItem(languageStorageKey);
  } catch {
    storedLanguage = null;
  }

  return translations[queryLanguage] ? queryLanguage : translations[storedLanguage] ? storedLanguage : 'en';
}

export function applyLanguage(language) {
  const activeLanguage = translations[language] ? language : 'en';
  const dictionary = translations[activeLanguage];

  document.documentElement.lang = activeLanguage;
  document.querySelectorAll('[data-i18n]').forEach((node) => {
    const value = dictionary[node.dataset.i18n];
    if (value) node.textContent = value;
  });
  document.querySelectorAll('[data-lang]').forEach((button) => {
    button.setAttribute('aria-pressed', String(button.dataset.lang === activeLanguage));
  });

  try {
    window.localStorage.setItem(languageStorageKey, activeLanguage);
  } catch {
    // Storage can be unavailable in private browsing; the page still works.
  }

  return activeLanguage;
}
